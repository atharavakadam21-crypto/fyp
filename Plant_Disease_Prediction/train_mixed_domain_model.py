"""Train a separate mixed-domain 38-class candidate model.

Inputs are generated by prepare_mixed_domain_data.py. The production model is
never loaded, overwritten, or required. EfficientNetV2B0 starts from ImageNet
weights and uses its built-in preprocessing (input pixels remain 0..255).

Example:
  python train_mixed_domain_model.py
  python train_mixed_domain_model.py --epochs 12 --head-epochs 3 --batch-size 32
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import os
import random
from collections import Counter
from pathlib import Path

import numpy as np
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers

SEED = 42
IMAGE_SIZE = (224, 224)
DEFAULT_BATCH_SIZE = 32


def read_manifest(path: Path, class_to_id: dict[str, int], expected_source: str | None = None):
    paths, labels = [], []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            label = row["label"]
            if label not in class_to_id:
                raise ValueError(f"Unknown class {label!r} in {path}")
            if expected_source and row["source"] != expected_source:
                continue
            image_path = Path(row["path"])
            if not image_path.is_file():
                raise FileNotFoundError(
                    f"Manifest image is missing: {image_path}\n"
                    "Re-run prepare_mixed_domain_data.py on this machine."
                )
            paths.append(str(image_path.resolve()))
            labels.append(class_to_id[label])
    return paths, labels


def make_dataset(paths, labels, batch_size, training, augment, seed):
    if not paths:
        raise ValueError("A dataset split is empty.")
    ds = tf.data.Dataset.from_tensor_slices((paths, labels))
    if training:
        ds = ds.shuffle(len(paths), seed=seed, reshuffle_each_iteration=True)

    def load_image(path, label):
        image_bytes = tf.io.read_file(path)
        image = tf.io.decode_image(image_bytes, channels=3, expand_animations=False)
        image.set_shape([None, None, 3])
        image = tf.image.resize(image, IMAGE_SIZE, method="bilinear")
        image = tf.cast(image, tf.float32)  # EfficientNetV2 built-in preprocessing expects 0..255.
        label = tf.one_hot(label, depth=NUM_CLASSES)
        return image, label

    ds = ds.map(load_image, num_parallel_calls=tf.data.AUTOTUNE)
    if augment:
        augmenter = keras.Sequential(
            [
                layers.RandomFlip("horizontal"),
                layers.RandomRotation(0.10),
                layers.RandomZoom(0.18),
                layers.RandomTranslation(0.08, 0.08),
                layers.RandomContrast(0.15),
            ],
            name="realistic_augmentation",
        )
        ds = ds.map(
            lambda x, y: (augmenter(x, training=True), y),
            num_parallel_calls=tf.data.AUTOTUNE,
        )
    ds = ds.batch(batch_size).prefetch(tf.data.AUTOTUNE)
    return ds


NUM_CLASSES = 38


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=Path, default=Path("data/mixed_domain_v1"))
    parser.add_argument("--output", type=Path, default=Path("trained_plant_disease_model_mixed_domain.keras"))
    parser.add_argument("--epochs", type=int, default=12, help="Fine-tuning epochs after head warm-up.")
    parser.add_argument("--head-epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=DEFAULT_BATCH_SIZE)
    parser.add_argument("--learning-rate", type=float, default=1e-4)
    parser.add_argument("--backbone-learning-rate", type=float, default=1e-5)
    parser.add_argument("--field-repeat-factor", type=float, default=10.0,
                        help="Controls mixed-domain epoch size; 10 means about 10 field-set passes per epoch across both sources.")
    parser.add_argument("--weights", choices=["imagenet", "none"], default="imagenet")
    args = parser.parse_args()

    if args.epochs < 1 or args.head_epochs < 0:
        parser.error("--epochs must be >= 1 and --head-epochs must be >= 0")
    if args.batch_size < 2:
        parser.error("--batch-size must be >= 2")
    if args.field_repeat_factor < 1:
        parser.error("--field-repeat-factor must be >= 1")

    tf.keras.utils.set_random_seed(SEED)
    random.seed(SEED)
    np.random.seed(SEED)

    data_dir = args.data_dir.resolve()
    train_manifest = data_dir / "train_manifest.csv"
    field_val_manifest = data_dir / "field_validation_manifest.csv"
    class_file = data_dir / "class_names.txt"
    for path in (train_manifest, field_val_manifest, class_file):
        if not path.is_file():
            raise FileNotFoundError(
                f"Required file missing: {path}\n"
                "Run prepare_mixed_domain_data.py first."
            )

    class_names = class_file.read_text(encoding="utf-8").splitlines()
    if len(class_names) != NUM_CLASSES or len(set(class_names)) != NUM_CLASSES:
        raise ValueError(f"Expected exactly {NUM_CLASSES} unique class names.")
    class_to_id = {name: i for i, name in enumerate(class_names)}

    original_paths, original_labels = read_manifest(train_manifest, class_to_id, "original")
    field_paths, field_labels = read_manifest(train_manifest, class_to_id, "PlantDoc")
    val_paths, val_labels = read_manifest(field_val_manifest, class_to_id, "PlantDoc")

    if not original_paths or not field_paths or not val_paths:
        raise ValueError(
            f"Empty split: original={len(original_paths)}, PlantDoc train={len(field_paths)}, "
            f"PlantDoc validation={len(val_paths)}. Check the label map and manifests."
        )

    # Sampling from each source with equal probability keeps the large clean
    # dataset from overwhelming field examples. Epoch length is capped so a
    # small field dataset is not replayed hundreds of times in one epoch.
    original_ds = make_dataset(
        original_paths, original_labels, args.batch_size, True, True, SEED
    ).unbatch().repeat()
    field_ds = make_dataset(
        field_paths, field_labels, args.batch_size, True, True, SEED + 1
    ).unbatch().repeat()
    train_ds = tf.data.Dataset.sample_from_datasets(
        [original_ds, field_ds],
        weights=[0.5, 0.5],
        seed=SEED,
        stop_on_empty_dataset=False,
    ).batch(args.batch_size).prefetch(tf.data.AUTOTUNE)

    # Keep validation field-only; never use the final external test set here.
    val_ds = make_dataset(
        val_paths, val_labels, args.batch_size, False, False, SEED
    )

    steps_per_epoch = min(
        math.ceil(len(original_paths) / args.batch_size),
        max(
            50,
            math.ceil(
                len(field_paths) * args.field_repeat_factor * 2 / args.batch_size
            ),
        ),
    )
    steps_per_epoch = max(1, steps_per_epoch)

    print("\n========== MIXED-DOMAIN TRAINING ==========")
    print(f"Classes: {len(class_names)}")
    print(f"Original training images: {len(original_paths):,}")
    print(f"PlantDoc training images: {len(field_paths):,}")
    print(f"PlantDoc field-validation images: {len(val_paths):,}")
    print(f"Steps per epoch: {steps_per_epoch}")
    print(f"Output candidate: {args.output.resolve()}")
    print("Production model will not be changed.")

    if args.weights == "imagenet":
        backbone = keras.applications.EfficientNetV2B0(
            include_top=False,
            weights="imagenet",
            input_shape=(*IMAGE_SIZE, 3),
            include_preprocessing=True,
        )
    else:
        backbone = keras.applications.EfficientNetV2B0(
            include_top=False,
            weights=None,
            input_shape=(*IMAGE_SIZE, 3),
            include_preprocessing=True,
        )

    backbone.trainable = False
    inputs = keras.Input(shape=(*IMAGE_SIZE, 3), name="leaf_image")
    x = backbone(inputs, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dropout(0.35)(x)
    x = layers.Dense(256, activation="relu")(x)
    x = layers.Dropout(0.25)(x)
    outputs = layers.Dense(NUM_CLASSES, activation="softmax", name="disease")(x)
    model = keras.Model(inputs, outputs, name="mixed_domain_plant_disease")

    loss_fn = keras.losses.CategoricalCrossentropy(label_smoothing=0.1)
    model.compile(
        optimizer=keras.optimizers.AdamW(learning_rate=args.learning_rate, weight_decay=1e-4),
        loss=loss_fn,
        metrics=["accuracy"],
    )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    best_path = args.output.with_name(args.output.stem + "_best.keras")
    callbacks = [
        keras.callbacks.ModelCheckpoint(
            str(best_path), monitor="val_loss", save_best_only=True, verbose=1
        ),
        keras.callbacks.EarlyStopping(
            monitor="val_loss", patience=4, restore_best_weights=True, verbose=1
        ),
        keras.callbacks.CSVLogger(str(args.output.with_suffix(".history.csv"))),
        keras.callbacks.TerminateOnNaN(),
    ]

    if args.head_epochs:
        print("\nStage 1/2: training classifier head...")
        model.fit(
            train_ds,
            validation_data=val_ds,
            epochs=args.head_epochs,
            steps_per_epoch=steps_per_epoch,
            callbacks=callbacks,
        )

    print("\nStage 2/2: fine-tuning upper backbone layers...")
    backbone.trainable = True
    # Keep the lower layers frozen and only fine-tune the upper part.
    freeze_until = max(0, len(backbone.layers) - 35)
    for layer in backbone.layers[:freeze_until]:
        layer.trainable = False
    # BatchNorm moving statistics can become unstable on a small field set.
    for layer in backbone.layers:
        if isinstance(layer, layers.BatchNormalization):
            layer.trainable = False

    model.compile(
        optimizer=keras.optimizers.AdamW(
            learning_rate=args.backbone_learning_rate, weight_decay=1e-4
        ),
        loss=loss_fn,
        metrics=["accuracy"],
    )
    model.fit(
        train_ds,
        validation_data=val_ds,
        initial_epoch=args.head_epochs,
        epochs=args.head_epochs + args.epochs,
        steps_per_epoch=steps_per_epoch,
        callbacks=callbacks,
    )

    # Reload the best field-validation checkpoint, then save to a new candidate path.
    if best_path.is_file():
        best_model = keras.models.load_model(best_path)
        best_model.save(args.output)
    else:
        model.save(args.output)

    metadata = {
        "model": args.output.name,
        "architecture": "EfficientNetV2B0",
        "input_size": list(IMAGE_SIZE),
        "num_classes": len(class_names),
        "class_names": class_names,
        "training_sources": ["original PlantVillage-style dataset", "PlantDoc train split"],
        "selection_metric": "PlantDoc field-validation loss",
        "production_model_modified": False,
        "seed": SEED,
    }
    metadata_path = args.output.with_suffix(".metadata.json")
    metadata_path.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print("\n========== TRAINING COMPLETE ==========")
    print(f"Candidate model: {args.output.resolve()}")
    print(f"Best checkpoint: {best_path.resolve()}")
    print(f"History CSV: {args.output.with_suffix('.history.csv').resolve()}")
    print(f"Metadata: {metadata_path.resolve()}")
    print("Do not replace the production model until the frozen test-set evaluation passes.")


if __name__ == "__main__":
    main()
